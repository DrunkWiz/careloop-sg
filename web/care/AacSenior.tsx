// One senior in the AAC caseload: today's decision, the open handover, and the befriending record,
// written from the decision log so staff don't fill in a form.
import { useEffect, useState } from 'react';
import type { CaseloadRow, LogDay } from '../shared/contract';
import { getLog } from '../shared/api';
import { BackLink, KIND_TITLE } from './HandoverView';
import { navigate } from './nav';

const fmtDay = (d: string) => new Date(d).toLocaleDateString('en-SG', { weekday: 'short', day: 'numeric', month: 'short' });
const fmtTime = (d: string) => new Date(d).toLocaleTimeString('en-SG', { hour: 'numeric', minute: '2-digit' });
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

function recordText(name: string, log: LogDay[]): string {
  const days = [...log].sort((a, b) => a.date.localeCompare(b.date));
  const replied = log.filter((d) => d.checkins.length).length;
  return [
    `Befriending record: ${name}`,
    `Period: ${fmtDay(days[0].date)} to ${fmtDay(days[days.length - 1].date)}`,
    'Generated by CareLoop from its decision log.',
    `Check-ins answered: ${replied} of ${log.length} days.`,
    '',
    ...days.map((d) => {
      const said = d.checkins.length
        ? d.checkins.map((c) => `Replied at ${fmtTime(c.time)}: "${c.raw_text}"`).join(' ') + '.'
        : 'No reply.';
      return `${fmtDay(d.date)}: ${said} CareLoop: ${cap(d.reason)}.`;
    }),
  ].join('\n');
}

export default function AacSenior({ row }: { row: CaseloadRow }) {
  const [log, setLog] = useState<LogDay[] | null | undefined>(undefined);
  const [copied, setCopied] = useState(false);
  const h = row.handover;

  useEffect(() => {
    getLog(row.senior.id).then(setLog, () => setLog(null));
  }, [row.senior.id]);

  const copy = async () => {
    if (!log) return;
    try {
      await navigator.clipboard.writeText(recordText(row.senior.name, log));
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  };

  return (
    <>
      <BackLink to="/care/aac" label="Caseload" />
      <h1>{row.senior.name}</h1>
      <p className="care-lead">
        {row.today.reason ? `Today: ${row.today.reason}.` : 'No decision yet today.'}
        {row.last_reply && <span className="care-muted"> Last replied {fmtDay(row.last_reply)}, {fmtTime(row.last_reply)}.</span>}
      </p>

      {h && (
        <button className="care-card care-card-handover" onClick={() => navigate(`/care/aac/handover/${h.id}`)}>
          <span className="care-card-title">
            {KIND_TITLE[h.kind]}
            {h.status !== 'open' && <span className="care-pill">You are handling it</span>}
          </span>
          <span>{cap(h.evidence.summary)}.</span>
          <span className="care-card-cta">{h.status === 'open' ? 'See the evidence and pick a step →' : 'See the evidence →'}</span>
        </button>
      )}

      <section className="care-card">
        <div className="aac-record-head">
          <h2>Befriending record, last 7 days</h2>
          {log && (
            <button className="care-link" onClick={copy}>
              {copied ? 'Copied' : 'Copy'}
            </button>
          )}
        </div>
        {log === undefined && <p className="care-muted">Loading…</p>}
        {log === null && (
          <p className="care-muted">
            The 7-day record isn't available from the server yet. Today's decision is above.
          </p>
        )}
        {log && (
          <>
            <p className="care-muted">
              Answered {log.filter((d) => d.checkins.length).length} of {log.length} check-ins. Written from CareLoop's
              decision log: nothing to fill in.
            </p>
            <ol className="care-timeline aac-record">
              {log.map((d) => (
                <li key={d.date}>
                  <span className="care-timeline-date">{fmtDay(d.date).replace(/^\w+, /, '')}</span>
                  <span>
                    {d.checkins.length ? (
                      d.checkins.map((c, i) => (
                        <span key={i} className="aac-said">
                          “{c.raw_text}”
                        </span>
                      ))
                    ) : (
                      <span className="aac-said is-none">No reply</span>
                    )}
                    <span className="aac-reason">
                      {d.rung === '0' ? '' : `Rung ${d.rung}. `}
                      {cap(d.reason)}.
                    </span>
                  </span>
                </li>
              ))}
            </ol>
          </>
        )}
      </section>
    </>
  );
}
