// One senior in the AAC caseload: the open handover (if any) and the befriending record,
// generated from the decision log so staff don't fill in a form.
import { useState } from 'react';
import type { CaseloadRow, Contact, LogDay } from '../shared/contract';
import { navigate } from './nav';

const fmtDay = (d: string) => new Date(d).toLocaleDateString('en-SG', { weekday: 'short', day: 'numeric', month: 'short' });
const fmtTime = (d: string) => new Date(d).toLocaleTimeString('en-SG', { hour: 'numeric', minute: '2-digit' });

function recordText(row: CaseloadRow, staff: Contact): string {
  const days = [...row.log].reverse(); // oldest first, as a record reads
  const replied = row.log.filter((d) => d.checkin).length;
  const lines = [
    `Befriending record: ${row.senior.name}`,
    `Period: ${fmtDay(days[0].decision.date)} to ${fmtDay(days[days.length - 1].decision.date)}`,
    `Prepared for: ${staff.name}. Generated by CareLoop from its decision log.`,
    `Check-ins answered: ${replied} of ${row.log.length} days.`,
    '',
    ...days.map((d) => `${fmtDay(d.decision.date)}: ${dayLine(d)}`),
  ];
  return lines.join('\n');
}

function dayLine(d: LogDay): string {
  const said = d.checkin ? `Replied at ${fmtTime(d.checkin.time)}: "${d.checkin.raw_text}". ` : 'No reply. ';
  return `${said}${d.decision.reason}`;
}

export default function AacSenior({ row, contact }: { row: CaseloadRow; contact: Contact }) {
  const [copied, setCopied] = useState(false);
  const h = row.handover;
  const replied = row.log.filter((d) => d.checkin).length;

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(recordText(row, contact));
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  };

  return (
    <>
      <button className="care-link care-back" onClick={() => navigate('/care/aac')}>
        ← Caseload
      </button>
      <h1>{row.senior.name}</h1>
      <p className="care-lead">{row.line}</p>

      {h && (
        <button className="care-card care-card-handover" onClick={() => navigate(`/care/aac/handover/${h.id}`)}>
          <span className="care-card-title">
            {h.kind === 'red_flag' ? 'Red flag' : 'Needs a next step'}
            {h.claimed_by_name && <span className="care-pill">{h.claimed_by_name} is handling it</span>}
          </span>
          <span>{h.evidence.summary}</span>
          <span className="care-card-cta">See the evidence and pick a step →</span>
        </button>
      )}

      <section className="care-card">
        <div className="aac-record-head">
          <h2>Befriending record, last 7 days</h2>
          <button className="care-link" onClick={copy}>
            {copied ? 'Copied' : 'Copy'}
          </button>
        </div>
        <p className="care-muted">
          Answered {replied} of {row.log.length} check-ins. Written from CareLoop's decision log: nothing to fill in.
        </p>
        <ol className="care-timeline aac-record">
          {row.log.map((d) => (
            <li key={d.decision.date}>
              <span className="care-timeline-date">{fmtDay(d.decision.date).replace(/^\w+, /, '')}</span>
              <span>
                {d.checkin ? (
                  <span className="aac-said">“{d.checkin.raw_text}”</span>
                ) : (
                  <span className="aac-said is-none">No reply</span>
                )}
                <span className="aac-reason">
                  {d.decision.rung === 0 ? '' : `Rung ${d.decision.rung}. `}
                  {d.decision.reason}
                </span>
              </span>
            </li>
          ))}
        </ol>
      </section>

      <section className="care-card">
        <h2>Likes</h2>
        <p className="care-muted">{row.senior.likes.join(', ')}. Suggestions use these and your centre's programmes.</p>
      </section>
    </>
  );
}
