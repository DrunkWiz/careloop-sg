// One senior in the AAC caseload: today's decision, the open handover, the day-by-day timeline, and the
// befriending record, written from the decision log so staff don't fill in a form.
import { useEffect, useState } from 'react';
import type { CaseloadRow, LogDay } from '../shared/contract';
import { getLog } from '../shared/api';
import { BackLink, KIND_TITLE } from './HandoverView';
import Timeline from './Timeline';
import { initials } from './FamilyHome';
import { cap, plainSummary, ruleText } from './plain';
import { navigate } from './nav';

const fmtDay = (d: string) => new Date(d).toLocaleDateString('en-SG', { weekday: 'short', day: 'numeric', month: 'short' });
const fmtTime = (d: string) => new Date(d).toLocaleTimeString('en-SG', { hour: 'numeric', minute: '2-digit' });

function recordText(name: string, log: LogDay[]): string {
  const days = [...log].sort((a, b) => a.date.localeCompare(b.date));
  const replied = log.filter((d) => d.checkins.length).length;
  return [
    `Befriending record: ${name}`,
    `Period: ${fmtDay(days[0].date)} to ${fmtDay(days[days.length - 1].date)}`,
    'Generated by CareLoop from its decision log. Synthetic demo data.',
    `Check-ins answered: ${replied} of ${log.length} days.`,
    '',
    ...days.map((d) => {
      const said = d.checkins.length
        ? d.checkins.map((c) => `Replied at ${fmtTime(c.time)}: "${c.raw_text}"`).join(' ') + '.'
        : 'No reply.';
      const what = d.reason ? `${cap(d.reason)} (rule ${d.rule_id})` : ruleText(d.rule_id, d.rung);
      return `${fmtDay(d.date)}: ${said} CareLoop: ${what}.`;
    }),
  ].join('\n');
}

export default function AacSenior({ row }: { row: CaseloadRow }) {
  const [log, setLog] = useState<LogDay[] | null | undefined>(undefined);
  const [copied, setCopied] = useState(false);
  const h = row.handover;

  useEffect(() => {
    getLog(row.senior.id, 14, row.contact_id).then(setLog, () => setLog(null));
  }, [row.senior.id, row.contact_id]);

  const week = log?.slice(0, 7) ?? null;
  const copy = async () => {
    if (!week) return;
    try {
      await navigator.clipboard.writeText(recordText(row.senior.name, week));
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  };

  return (
    <>
      <BackLink to="/care/aac" label="Caseload" />
      <div className="hero-top senior-head">
        <span className="avatar" aria-hidden="true">
          {initials(row.senior.name)}
        </span>
        <div>
          <h1>{row.senior.name}</h1>
          <p className="care-muted">
            {row.last_reply ? `Last replied ${fmtDay(row.last_reply)}, ${fmtTime(row.last_reply)}` : 'No replies yet'}
            {' · '}
            {row.senior.language === 'zh' ? 'Mandarin' : row.senior.language === 'en-SG' ? 'Singlish' : 'English'}
          </p>
        </div>
      </div>
      <p className="care-lead">Today: {row.today.reason ? `${cap(row.today.reason)}.` : 'no decision yet.'}</p>

      {h && (
        <button className="care-card care-card-handover" onClick={() => navigate(`/care/aac/handover/${h.id}`)}>
          <span className="care-card-title">
            {KIND_TITLE[h.kind]}
            {h.status !== 'open' && <span className="care-pill">You are handling it</span>}
          </span>
          <span>{plainSummary(h, row.senior.name)}</span>
          <span className="care-card-cta">{h.status === 'open' ? 'See the evidence and pick a step →' : 'See the evidence →'}</span>
        </button>
      )}

      {log && log.length > 0 && <Timeline log={log} name={row.senior.name} />}

      <section className="care-card">
        <div className="aac-record-head">
          <h2>Befriending record, last 7 days</h2>
          {week && (
            <button className="care-link" onClick={copy}>
              {copied ? 'Copied' : 'Copy'}
            </button>
          )}
        </div>
        {log === undefined && <p className="care-muted">Loading…</p>}
        {log === null && <p className="care-muted">The 7-day record isn't available from the server yet.</p>}
        {week && (
          <p className="care-muted">
            Answered {week.filter((d) => d.checkins.length).length} of {week.length} check-ins. Written from CareLoop's
            decision log, ready to paste into your centre's report: nothing to fill in.
          </p>
        )}
      </section>
    </>
  );
}
